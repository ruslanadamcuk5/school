def band_for_grade(grade: int) -> dict[str, Any]:
    try:
        value = int(grade)
    except (TypeError, ValueError):
        value = 3
    for band in BANDS:
        if value in band["grades"]:
            return band
    return BANDS[0] if value < 5 else BANDS[-1]


def tests_for_grade(grade: int) -> list[dict[str, Any]]:
    band = band_for_grade(grade)
    return list(_TESTS_BY_BAND.get(band["key"], []))


def get_test(slug: str) -> dict[str, Any] | None:
    return _TESTS_BY_SLUG.get((slug or "").strip())


