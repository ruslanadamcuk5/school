def _lvl(
    label: str,
    parent: str,
    student: str,
    advice: list[str],
    title: str = "",
) -> dict[str, Any]:
    return {
        "label": label,
        "parent": parent,
        "student": student,
        "advice": advice,
        "title": title or label,
    }


def _scale(
    label: str,
    icon: str,
    low: dict[str, Any],
    mid: dict[str, Any],
    high: dict[str, Any],
    *,
    good_high: bool = True,
) -> dict[str, Any]:
    return {
        "label": label,
        "icon": icon,
        "good_high": good_high,
        "levels": {"low": low, "mid": mid, "high": high},
    }


